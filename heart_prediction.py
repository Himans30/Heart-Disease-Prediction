"""importing the dependencies"""

import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score

"""Data Collection and processing

"""

#loading the csv data to a pandas Data frame
heart_data = pd.read_csv('heart.csv')

#print first 10 rows of data set
heart_data.head(10)

#print last 10 row of the data set
heart_data.tail(10)

#no of rows and column in data set
heart_data.shape

#getting some info about the data
heart_data.info()

# check for missing values
heart_data.isnull().sum()

# statistical measure about the data
heart_data.describe()

#checking the distribution of target variable
heart_data['target'].value_counts()

"""1--> defective heart
0--> healthy heart

spiliting the features and target
"""

X=heart_data.drop(columns='target',axis=1)
Y=heart_data['target']

print(X)

print(Y)

"""splitting the data into train data and test data

"""

X_train,X_test,Y_train,Y_test=train_test_split(X,Y,test_size=0.2,stratify=Y,random_state=2)

print(X.shape,X_train.shape,X_test.shape)

"""Model Trainning

Logistic Regression
"""

model=LogisticRegression()

#trainning the logisticRegression model with trainning data
model.fit(X_train,Y_train)

"""Model Evalution

Accuracy Score
"""

#accuracy on trainning data
X_train_prediction=model.predict(X_train)
training_data_accuracy=accuracy_score(X_train_prediction,Y_train)

print('Accuracy on Trainning data:',training_data_accuracy)

#accuracy on trainning data
X_test_prediction=model.predict(X_test)
test_data_accuracy=accuracy_score(X_test_prediction,Y_test)

print('Accuracy on Test data:',test_data_accuracy)

"""Building Predictive System"""

